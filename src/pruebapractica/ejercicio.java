package pruebapractica;

public class ejercicio {

	public static void pelo(int opciones) {
		
		switch (opciones) {
		case 1: System.out.println("WWWWWWWWW");
		break;
		case 2: System.out.println("\\\\/////");
		break;
		case 3: System.out.println("|||||||");
		break;
		case 4: System.out.println("|||||||||");
		break;
		}
	}

		public static void ojos(int opciones) {
		switch (opciones) {
		case 1: System.out.println("| o o |");
		break;
		case 2: System.out.println("|-(· ·)-|");
		break;
		case 3: System.out.println("|-(o o)-|");
		break;
		case 4: System.out.println("| \\   / |");
		break;
		}
	}
		
		public static void orejasNariz(int opciones) {
		switch (opciones) {
		case 1: System.out.println("@  J  @");
		break;
		case 2: System.out.println("{  \"  }");
		break;
		case 3: System.out.println("[ j ]");
		break;
		case 4: System.out.println("< - >");
		break;
	}
		
		switch (opciones) {
		case 1: return "WWWWWWWWW";
		case 2: return "\\\//////";
		case 3: return "|||||||";
		case 4: return "|||||||||";
	}
		
		switch (opciones) {
		case 1: return "WWWWWWWWW";
		case 2: return "\\\//////";
		case 3: return "|||||||";
		case 4: return "|||||||||";
	}
}
}
